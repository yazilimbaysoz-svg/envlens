"""Safe generation of ``.env.example`` templates from detected variable names."""

from __future__ import annotations

from pathlib import Path

from envlens.config import Config, is_env_file, iter_files
from envlens.envfiles import parse_dotenv
from envlens.manifests import scan_manifests
from envlens.scanner import scan_sources, scan_workflow_references

_HEADER = "# Generated by envlens - add a short comment and a safe placeholder for each key."


def sync_example(
    root: Path, config: Config | None = None, output: str = ".env.example"
) -> list[str]:
    """Append missing variable names to the template, never writing real values."""
    settings = config or Config.load(root)
    references = scan_sources(root, settings) + scan_workflow_references(root, settings)
    names = {ref.name for ref in references if ref.name not in settings.ignore}
    for path in iter_files(root, settings, predicate=is_env_file):
        names.update(item.name for item in parse_dotenv(path) if item.name not in settings.ignore)
    names.update(
        item.name for item in scan_manifests(root, settings) if item.name not in settings.ignore
    )

    target = root / output
    existing_text = target.read_text(encoding="utf-8", errors="replace") if target.is_file() else ""
    existing_names = (
        {item.name for item in parse_dotenv(target, is_example=True)} if target.is_file() else set()
    )
    added = sorted(names - existing_names)
    if not added:
        return []

    content = existing_text.rstrip("\n") or _HEADER
    content += "\n\n# Added by envlens sync-example (fill in safe placeholders)\n"
    content += "\n".join(f"{name}=" for name in added) + "\n"
    target.write_text(content, encoding="utf-8")
    return added
